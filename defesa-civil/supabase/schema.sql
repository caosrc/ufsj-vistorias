-- Todo usuário autenticado pertence ao mesmo espaço de trabalho compartilhado.
-- Usuários anônimos não recebem políticas de leitura ou gravação.
do $$
declare
  tabela text;
begin
  foreach tabela in array array[
    'ocorrencias', 'vistorias', 'imoveis', 'areas_risco',
    'vistoria_monitoramento', 'monitoramento_relatorios', 'monitoramento_fotos',
    'arquivos_app', 'precipitacoes', 'escala_estado', 'materiais',
    'checklists_ferramental', 'emprestimos', 'equipamentos_campo',
    'checklists_viatura', 'planejamentos', 'monitoramento_cnl_cotas',
    'radar_bilhetes', 'push_subscriptions', 'sos_ativos_db',
    'curral_registros', 'procon_relatorios'
  ] loop
    execute format('alter table public.%I enable row level security', tabela);
    execute format('drop policy if exists shared_authenticated_all on public.%I', tabela);
    execute format(
      'create policy shared_authenticated_all on public.%I for all to authenticated using (true) with check (true)',
      tabela
    );
    execute format('grant select, insert, update, delete on public.%I to authenticated', tabela);
  end loop;
end $$;

alter table public.profiles enable row level security;
